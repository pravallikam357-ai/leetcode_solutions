#  Problem Description:
# Convert the given string to lower case.

#  Approach:
# convert the given string to lower casee by using .lower() function.

#  Time Complexity: O(n)
#  Space Complexity: O(n)
class Solution(object):
    def toLowerCase(self, s):
       return s.lower()
        
